/**
 * Normalizes strings for robust matching of slugs, names, and synonyms.
 */
function normalizeQuery(input: string): string {
  return input
    .toLowerCase()
    .replace(/[\u200c\u200d\u200e\u200f\u00a0]/g, "")
    .replace(/[_\-–—]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

/**
 * Returns all available wiki plants.
 */
export function getAllWikiPlants(): WikiPlant[] {
  return wikiPlants
}

/**
 * Finds a wiki plant by primary slug, alternate English/Persian slug, or exact names.
 */
export function getWikiPlantBySlug(slug: string): WikiPlant | undefined {
  if (!slug || typeof slug !== "string" || !slug.trim()) return undefined
  const decoded = decodeURIComponent(slug).trim().toLowerCase()
  const normalized = normalizeQuery(decoded)
  if (!normalized) return undefined

  return wikiPlants.find((plant) => {
    if (plant.slug.toLowerCase() === decoded) return true
    if (normalizeQuery(plant.slug) === normalized) return true
    if (
      plant.alternateSlugs?.some(
        (s) => s.toLowerCase() === decoded || normalizeQuery(s) === normalized,
      )
    ) {
      return true
    }
    if (normalizeQuery(plant.nameFa).includes(normalized)) return true
    if (plant.nameEn.toLowerCase() === decoded) return true
    if (plant.scientificName.toLowerCase() === decoded) return true
    return false
  })
}

/**
 * Returns the highlighted / popular wiki plants.
 */
export function getPopularWikiPlants(): WikiPlant[] {
  return wikiPlants.filter((plant) => plant.isPopular)
}

/**
 * Filters wiki plants by category or tag.
 */
export function getWikiPlantsByCategory(category: string): WikiPlant[] {
  if (!category) return wikiPlants
  const normCat = normalizeQuery(category)
  return wikiPlants.filter(
    (plant) =>
      (plant.category && normalizeQuery(plant.category).includes(normCat)) ||
      plant.tags.some((tag) => normalizeQuery(tag).includes(normCat)),
  )
}

/**
 * Searches wiki plants by keyword across names, scientific names, and care descriptions.
 */
export function searchWikiPlants(query: string): WikiPlant[] {
  if (!query) return wikiPlants
  const norm = normalizeQuery(query)
  return wikiPlants.filter((plant) => {
    return (
      normalizeQuery(plant.nameFa).includes(norm) ||
      plant.nameEn.toLowerCase().includes(norm) ||
      plant.scientificName.toLowerCase().includes(norm) ||
      normalizeQuery(plant.description).includes(norm) ||
      plant.tags.some((tag) => normalizeQuery(tag).includes(norm))
    )
  })
}

/**
 * Returns related wiki plants sharing tags or botanical families.
 */
export function getRelatedWikiPlants(plant: WikiPlant, limit = 3): WikiPlant[] {
  return wikiPlants
    .filter((p) => p.slug !== plant.slug)
    .map((p) => {
      let score = 0
      if (p.family === plant.family) score += 3
      if (p.difficulty === plant.difficulty) score += 1
      const commonTags = p.tags.filter((t) => plant.tags.includes(t))
      score += commonTags.length * 2
      return { plant: p, score }
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.plant)
}
