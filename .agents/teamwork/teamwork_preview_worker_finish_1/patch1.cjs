let applied = 0;
for (const [slug, item] of Object.entries(listSnippets)) {
  const searchPattern = item.h2 + '</h2>\\n      <p class=\\"text-slate-600 mb-4\\">';
  const idx = content.indexOf(searchPattern);
  if (idx !== -1) {
    // Find the end of this paragraph: </p>
    const pEnd = content.indexOf('</p>', idx);
    if (pEnd !== -1) {
      const insertionPoint = pEnd + 4; // right after </p>
      const before = content.slice(0, insertionPoint);
      const after = content.slice(insertionPoint);
      content = before + "\\n\\n      " + item.list.trim() + after;
      applied++;
    } else {
      console.error(`</p> not found for ${slug}`);
    }
  } else {
    console.error(`Search pattern not found for ${slug}`);
  }
}

console.log(`Applied ${applied} of ${Object.keys(listSnippets).length} list patches.`);
fs.writeFileSync(filePath, content, "utf-8");
